"""Generate config/calibration.sim.yaml: a fully taught machine that exists
only in simulation, so a dry run works on a fresh clone.

Real calibration.yaml is written by the GUI from actual jogged positions. This
file is invented, and is used only when PAPA_SIM=1 and no real one exists.
"""
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
ROWS, SLOT_ROWS, SLOT_COLS = 15, 3, 3


def build() -> dict:
    swabs, sid = [], 1
    for row in range(1, ROWS + 1):
        for side in ("right", "left"):
            swabs.append({
                "id": sid, "row": row, "side": side,
                "x": 112.4 if side == "right" else 98.4,
                "y": round(30.0 + (row - 1) * 12.0, 2),
                "z_grip": 14.0, "calibrated": True,
            })
            sid += 1

    slots = []
    for r in range(SLOT_ROWS):
        for c in range(SLOT_COLS):
            slots.append({
                "id": r * SLOT_COLS + c + 1,
                "x": round(150.0 + c * 60.0, 2),
                "y": round(240.0 - r * 60.0, 2),
                "calibrated": True,
            })

    return {
        "substrate": {"width_mm": 25.0, "length_mm": 75.0, "pattern_size_mm": 25.0},
        "swab_rack": {"rows": ROWS, "swabs_per_slide": 2, "swabs": swabs},
        "slide_slots": {"rows": SLOT_ROWS, "cols": SLOT_COLS, "slots": slots},
        "load_cell": {"x": 30.0, "y": 40.0, "z_safe": 25.0,
                      "scale_counts_per_g": 1.0, "tare_counts": 0},
        "disposal": {"x": 10.0, "y": 10.0, "z_release": 20.0},
        "slide_surface_offset_mm": 0.4,
        "gripper": {"open_us": 1000, "closed_us": 2000},
        "detection": {
            "camera_to_machine": {
                "points_px": [[320, 180], [1600, 180], [1600, 900], [320, 900]],
                "points_mm": [[40.0, 260.0], [300.0, 260.0], [300.0, 40.0], [40.0, 40.0]],
            },
            "swab_stem_mm": 2.54,
            "swab_roi_mm": 4.0,
            "film_hsv": {"h": [100, 130], "s_min": 80, "v_min": 60},
            "stem_hsv": {"h": [102, 128], "s_min": 90, "v_min": 55},
            "slide_min_blue_fraction": 0.35,
            "swab_min_blue_fraction": 0.30,
            "slide_misaligned_fraction": 0.12,
        },
    }


if __name__ == "__main__":
    out = ROOT / "config" / "calibration.sim.yaml"
    header = (
        "# Generated by scripts/make_sim_calibration.py - simulation only.\n"
        "# Invented positions. Used when PAPA_SIM=1 and no calibration.yaml exists.\n"
    )
    out.write_text(header + yaml.safe_dump(build(), sort_keys=False))
    print(f"wrote {out}")
